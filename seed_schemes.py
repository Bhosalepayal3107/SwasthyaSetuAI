def seed_database():
    """Insert all schemes if the database is not fully populated."""
    init_db()
    conn = get_db()
    count = conn.execute("SELECT COUNT(*) FROM schemes").fetchone()[0]
    conn.close()

    if count >= 100:
        print(f"Database already has {count} schemes. Skipping seed.")
        print("To re-seed, delete swasthyasetu.db and run again.")
        return

    print(f"Seeding {len(SCHEMES_DATA)} government healthcare schemes...")
    conn = get_db()
    for s in SCHEMES_DATA:
        exists = conn.execute("SELECT id FROM schemes WHERE name = ?", (s["name"],)).fetchone()
        if not exists:
            conn.execute("""
                INSERT INTO schemes
                    (name, short_tag, category, govt_level, description, who_benefits,
                     eligibility_rules, required_documents, benefits_text, covered_treatments,
                     official_website, application_process, states_applicable,
                     age_min, age_max, income_limit, match_tags, is_active, color)
                VALUES
                    (:name, :short_tag, :category, :govt_level, :description, :who_benefits,
                     :eligibility_rules, :required_documents, :benefits_text, :covered_treatments,
                     :official_website, :application_process, :states_applicable,
                     :age_min, :age_max, :income_limit, :match_tags, :is_active, :color)
            """, s)
    conn.commit()
    conn.close()
    print("[OK] Successfully seeded schemes into the database!")
    print("Admin credentials: username=admin, password=swasthyasetu2024")


if __name__ == "__main__":
    seed_database()
